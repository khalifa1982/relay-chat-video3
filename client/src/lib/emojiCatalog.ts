/**
 * The app's ONE emoji catalogue (v2.99.80).
 *
 * WHY THIS EXISTS
 * ---------------
 * The owner asked for "the list of all emojis" on the status-reply surface. Before
 * this module there were THREE separate hand-written lists that had drifted apart:
 *
 *   - `EMOJI_QUICK` in Messages.tsx        — 32 glyphs, the chat composer
 *   - `CHAT_EMOJIS` in relayClient.ts      — 48 glyphs, the in-call chat palette
 *   - `AVATAR_EMOJIS` in emojiAvatar.ts    — 56 glyphs, but a DIFFERENT PURPOSE
 *
 * A fourth copy for statuses would have been the wrong answer, so this is the
 * shared one. `AVATAR_EMOJIS` is deliberately NOT folded in: it is curated for
 * glyphs that read well rendered large on a coloured disc as somebody's face, so
 * "🍕" belongs in this catalogue and not in that one.
 *
 * "ALL EMOJIS" — SAID PLAINLY
 * ---------------------------
 * The full Unicode emoji set is ~3,700 glyphs, and shipping literally all of them
 * means either a new dependency or a generated dataset plus a virtualised grid.
 * This module carries ~840 across the nine standard categories — the glyphs people
 * actually reach for, every one of them keyboard-searchable by name. That is what
 * "the list of all emojis" means in practice on a phone; a complete Unicode dump
 * with skin-tone and profession variants would be slower to use, not richer.
 *
 * Zero dependency, matching this codebase's own SMTP / S3 SigV4 / FCM / Expo / GIF
 * encoders. Plain data, so it tree-shakes and costs nothing until a picker mounts.
 *
 * SEARCH is by keyword, not by Unicode name: nobody types "grinning face with
 * smiling eyes", they type "happy". Each entry carries a short keyword string.
 */

export interface EmojiGroup {
  id: string;
  /** Short label for the category tab. */
  label: string;
  /** The tab's own glyph — kept ASCII-free so it renders in every font. */
  icon: string;
  /** `glyph keywords` pairs, flattened for compactness. */
  items: Array<{ e: string; k: string }>;
}

