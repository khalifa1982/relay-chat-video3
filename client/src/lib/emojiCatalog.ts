/**
 * The six glyphs offered as one-tap reactions.
 *
 * Deliberately short: a quick-reaction row is for the tap you make without
 * thinking, and a wall of choices defeats that. The full catalogue is one tap
 * further in. Ordered by how often people actually reach for them.
 */
export const REACTION_QUICK = ["❤️", "😂", "😮", "😢", "👍", "🔥"] as const;

/**
 * Every glyph, flat and DEDUPED. Built lazily so an unused import costs nothing.
 *
 * A few glyphs are deliberately cross-listed — 🧗 is both a person and an
 * activity, 😻 is both a smiley and a heart — because somebody looking for a
 * climber will look in either tab. That is right for browsing and wrong for a
 * flat list, where a repeat becomes a duplicate React key.
 */
let flatCache: string[] | null = null;
export function allEmoji(): string[] {
  if (!flatCache) flatCache = Array.from(new Set(EMOJI_GROUPS.flatMap((g) => g.items.map((i) => i.e))));
  return flatCache;
}

/** How many glyphs the catalogue carries — used by tests and the picker's label. */
export function emojiCount(): number {
  return allEmoji().length;
}

/**
 * Keyword search.
 *
 * Matches a whole keyword or a keyword PREFIX ("lau" -> "laugh"), never an
 * infix: an infix match on two-letter queries returns most of the catalogue,
 * which is indistinguishable from no filter. An empty query returns [] rather
 * than everything, so the caller can tell "not searching" from "no results".
 */
export function searchEmoji(query: string, limit = 120): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  // Deduped: a cross-listed glyph (🧗 is under both People and Activity) would
  // otherwise appear twice in one result grid, which is a duplicate React key.
  const seen = new Set<string>();
  const out: string[] = [];
  for (const g of EMOJI_GROUPS) {
    for (const it of g.items) {
      if (seen.has(it.e)) continue;
      // The glyph itself matches, so pasting an emoji into the box finds it.
      if (it.e === q || it.k.split(" ").some((w) => w.startsWith(q))) {
        seen.add(it.e);
        out.push(it.e);
        if (out.length >= limit) return out;
      }
    }
  }
  return out;
}

/**
 * Is this string a SINGLE emoji? Used to decide whether a reply is a one-tap
 * reaction (rendered as one large glyph) or a sentence.
 *
 * Deliberately narrower than `isEmojiOnly` in Messages.tsx, which admits up to
 * ~8 composed glyphs because a whole bubble of "😂😂😂" should still render big.
 * Here the question is "did they tap a reaction button", and that is exactly one.
 *
 * Built through the RegExp CONSTRUCTOR, not a literal: `\p{…}` property escapes
 * need the `u` flag, and a `u`-flagged literal trips TS1501 against this repo's
 * downlevel target (the same workaround `Messages.tsx:172` already uses). The
 * try/catch covers an engine without Unicode property escapes at all.
 */
export function isSingleEmoji(body: string | null | undefined): boolean {
  const s = (body ?? "").trim();
  if (!s || s.length > 24) return false;
  try {
    // ‍ = ZWJ, ️ = variation selector — a flag or "heart on fire" is
    // several code points joined by them, and is still ONE glyph.
    const re = new RegExp(
      "^(?:\\p{Extended_Pictographic}|\\p{Emoji_Component}|\\u200d|\\ufe0f)+$",
      "u"
    );
    if (!re.test(s)) return false;
    // One composed glyph, so segment rather than counting code points.
    const Seg = (Intl as unknown as { Segmenter?: new (l?: string, o?: object) => { segment(s: string): Iterable<unknown> } }).Segmenter;
    if (Seg) return Array.from(new Seg(undefined, { granularity: "grapheme" }).segment(s)).length === 1;
    return true; // no Segmenter: the regex already proved it is emoji-only
  } catch {
    return false;
  }
}
